#!/usr/bin/env node
// Regenerates themes.js and style.css's pre-JS palettes from Omarchy themes.
//
//   git clone --depth 1 https://github.com/basecamp/omarchy /tmp/omarchy
//   node tools/gen-themes.mjs /tmp/omarchy/themes
//
// Every directory given holds <theme>/colors.toml (Omarchy's own themes, or
// ~/.config/omarchy/themes for installed ones); a later directory wins for a
// theme both define. Only colors.toml is read: nothing in a theme runs.

import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { parseColorsToml, resolveColors, themeName, paletteVars, PALETTE_KEYS } from "../colors.js";

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const DEFAULT_DARK = "tokyo-night";
const DEFAULT_LIGHT = "catppuccin-latte";
const BEGIN = "/* BEGIN GENERATED OMARCHY PALETTES (tools/gen-themes.mjs) */";
const END = "/* END GENERATED OMARCHY PALETTES */";

const dirs = process.argv.slice(2);
if (!dirs.length) {
  console.error("usage: node tools/gen-themes.mjs <omarchy-themes-dir> [...]");
  process.exit(2);
}

const found = new Map();
for (const dir of dirs) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (!entry.isDirectory() && !entry.isSymbolicLink()) continue;
    if (!/^[a-z0-9][a-z0-9-]*$/.test(entry.name)) continue;
    const file = path.join(dir, entry.name, "colors.toml");
    if (!fs.existsSync(file)) continue;
    const colors = resolveColors(parseColorsToml(fs.readFileSync(file, "utf8")));
    if (!colors) {
      console.warn(`skipped ${entry.name}: no background and foreground`);
      continue;
    }
    found.set(entry.name, colors);
  }
}
for (const id of [DEFAULT_DARK, DEFAULT_LIGHT]) {
  if (!found.has(id)) throw new Error(`The default theme ${id} is missing`);
}

// Alphabetical, as `omarchy theme list` prints them.
const themes = [...found.keys()].sort().map((id) => {
  const { mode, ...colors } = found.get(id);
  return { id, name: themeName(id), mode, colors };
});

const js = `// Omarchy's themes as Hacker paints them. Generated by tools/gen-themes.mjs
// from each theme's colors.toml in https://github.com/basecamp/omarchy (MIT);
// re-run it rather than editing this file.

export const DEFAULT_DARK = ${JSON.stringify(DEFAULT_DARK)};
export const DEFAULT_LIGHT = ${JSON.stringify(DEFAULT_LIGHT)};

// One theme per line, as JSON, so tools can read it without running it.
export const THEMES = [
${themes.map((t) => `  ${JSON.stringify(t)},`).join("\n")}
];
`;
fs.writeFileSync(path.join(ROOT, "themes.js"), js);

function block(selector, theme, indent) {
  const vars = paletteVars({ ...theme.colors });
  const lines = [`color-scheme: ${theme.mode};`, ...Object.entries(vars).map(([k, v]) => `${k}: ${v};`)];
  return `${indent}${selector} {\n${lines.map((l) => `${indent}  ${l}`).join("\n")}\n${indent}}`;
}

const dark = themes.find((t) => t.id === DEFAULT_DARK);
const light = themes.find((t) => t.id === DEFAULT_LIGHT);
const css = [
  BEGIN,
  `/* Before main.js applies the saved theme: ${dark.name}, or ${light.name} on a`,
  ` * light system, so nobody sees the wrong scheme flash. main.js then sets the`,
  ` * same properties inline for whichever theme is chosen. */`,
  block(":root", dark, ""),
  "",
  "@media (prefers-color-scheme: light) {",
  block(":root:not([data-vn-theme])", light, "  "),
  "}",
  END,
].join("\n");

const stylePath = path.join(ROOT, "style.css");
const style = fs.readFileSync(stylePath, "utf8");
const start = style.indexOf(BEGIN);
const stop = style.indexOf(END);
if (start < 0 || stop < start) throw new Error("style.css lacks the generated palette markers");
fs.writeFileSync(stylePath, style.slice(0, start) + css + style.slice(stop + END.length));

console.log(`Wrote ${themes.length} themes (${themes.filter((t) => t.mode === "dark").length} dark, ` +
  `${themes.filter((t) => t.mode === "light").length} light); ${PALETTE_KEYS.length} keys each.`);
